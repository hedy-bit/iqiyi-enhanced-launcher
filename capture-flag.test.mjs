import {test} from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('./capture-flag-guard.js',import.meta.url),'utf8');
test('capture flag survives movie changes and restores the latest original flag',()=>{
  const values={playMixer:{forbid_record_screen:true,title:'first'}};
  const store={getProp:k=>values[k],setProp(k,v){values[k]=v;return true;}};
  const original=store.setProp;
  let tick,cleared=false;
  const window={webpackChunk_iqiyi_webapp:{push:x=>x[2](()=>({M_:store}))}};
  const context=vm.createContext({window,setInterval:fn=>(tick=fn,1),clearInterval:()=>{cleared=true;}});
  assert.equal(vm.runInContext(source,context).current,false);
  const next={forbid_record_screen:true,title:'second'};
  store.setProp('playMixer',next);
  assert.equal(next.forbid_record_screen,true);
  assert.equal(values.playMixer.forbid_record_screen,false);
  assert.equal(values.playMixer.title,'second');
  store.setProp('unrelated',42);
  assert.equal(values.unrelated,42);
  values.playMixer={forbid_record_screen:true,title:'third'};
  tick();
  assert.equal(values.playMixer.forbid_record_screen,false);
  vm.runInContext(source,context);
  window.__iqiyiCaptureFlagGuardV1.stop();
  assert.equal(store.setProp,original);
  assert.equal(values.playMixer.forbid_record_screen,true);
  assert.equal(values.playMixer.title,'third');
  assert.equal(cleared,true);
});
